// Build the browser answer keys from the numbered source transcription.
import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const sources = JSON.parse(await readFile(new URL('data/imports/cambridge-4-listening-answers.json', root), 'utf8'));
const tracks = JSON.parse(await readFile(new URL('dist/listening/cambridge-04/catalog.json', root), 'utf8'));

function alternatives(text) {
  // Slashes inside parentheses describe optional prefixes, not whole answers.
  const options = text.split(/\/(?![^()]*\))/).map(s => s.trim()).filter(Boolean);
  return options.flatMap(option => {
    const optional = option.match(/\(([^)]+)\)/);
    if (!optional) return [option];
    return ['', ...optional[1].split('/').map(s => s.trim())].map(prefix => option.replace(optional[0], prefix).replace(/\s+/g, ' ').trim());
  });
}
const extraVariants = {
  '1:5': ['13 February', 'February 13th', 'February 13', '13th Feb', '13 Feb', 'Feb 13', 'Feb 13th'],
  '3:1': ['1-1/2 years', '1 1/2 years', '1.5 years', 'one and a half years'],
  '4:4': ['10 December', 'December 10th', 'December 10', '10th Dec', '10 Dec', 'Dec 10', 'Dec 10th'],
};
// These single numbered questions require both items, in either order.
const unorderedItems = {
  '1:11': ['coal', 'firewood'],
  '3:35': ['traffic', 'parking'],
  '3:38': ['D', 'F'],
  '3:40': ['A', 'C'],
};
// Each answer box earns one point; the pair can be given in either order.
const choiceGroups = {
  '2:3': [{numbers: [25, 26], letters: ['B', 'C']}],
  '2:4': [{numbers: [39, 40], letters: ['D', 'E']}],
  '4:4': [{numbers: [39, 40], letters: ['B', 'E']}],
};
const keys = {};
for (const track of tracks) {
  const source = sources.find(s => s.test === track.test);
  const questions = track.questions.map(({number}) => {
    const display = source.answers[number];
    if (!display) throw Error(`Missing Test ${track.test} Question ${number}`);
    const id = `${track.test}:${number}`;
    const accepted = id === '3:1' ? extraVariants[id] : [...alternatives(display), ...(extraVariants[id] || [])];
    return {number, display, accepted: [...new Set(accepted)], ...(unorderedItems[id] ? {items: unorderedItems[id]} : {})};
  });
  keys[track.id] = {source: source.source, questions, choiceGroups: choiceGroups[`${track.test}:${track.part}`] || []};
}
const output = '// Generated by scripts/build-listening-answers.mjs. Source URLs and original answer wording are retained.\nexport const LISTENING_ANSWERS = ' + JSON.stringify(keys, null, 2) + ';\n';
await Promise.all(['dist/listening-answers.js', 'listening-answers.js'].map(path => writeFile(new URL(path, root), output)));
console.log('Built 16 section answer keys (160 questions).');
