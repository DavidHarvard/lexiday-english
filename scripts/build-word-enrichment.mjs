import {readFile,readdir,writeFile,mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';
import {courseMap,wordMap} from '../dist/data.js';
const root=fileURLToPath(new URL('../',import.meta.url)),dir=join(root,'data/word-enrichment');
const expected=new Set([...courseMap['ielts-basic'].words,...courseMap['ielts-plus'].words]);
for(const id of [...expected])for(const note of wordMap[id].notes)if(!wordMap[note.word])expected.add(note.word);
const result={},errors=[];
for(const name of (await readdir(dir)).filter(name=>/^part-[\w-]+\.jsonl$/.test(name)).sort()){
 const text=await readFile(join(dir,name),'utf8');
 for(const [index,line] of text.split(/\r?\n/).entries()){
  if(!line.trim())continue;
  let row;try{row=JSON.parse(line);}catch{errors.push(`${name}:${index+1} invalid JSON`);continue;}
  if(!expected.has(row.id)||result[row.id]){errors.push(`${name}:${index+1} unknown or duplicate id ${row.id}`);continue;}
  if(!Array.isArray(row.entries)||!row.entries.length){errors.push(`${row.id}: missing entries`);continue;}
  const seen=new Set();
  for(const entry of row.entries){
   const key=entry.pos+'|'+entry.meaning;
   if(seen.has(key))errors.push(`${row.id}: duplicate meaning ${key}`);seen.add(key);
   if(typeof entry.pos!=='string'||!entry.pos||entry.pos==='词条'||typeof entry.meaning!=='string'||!/[\u3400-\u9fff]/.test(entry.meaning)||typeof entry.definition!=='string'||!entry.definition.trim())errors.push(`${row.id}: incomplete sense metadata`);
   if(!Array.isArray(entry.examples)||entry.examples.length<2||new Set(entry.examples.map(ex=>ex.en)).size!==entry.examples.length)errors.push(`${row.id}: each meaning requires distinct examples, at least two`);
   for(const ex of entry.examples||[])if(typeof ex.en!=='string'||!/[a-z]/i.test(ex.en)||typeof ex.zh!=='string'||!/[\u3400-\u9fff]/.test(ex.zh)||/[<>]/.test(ex.en+ex.zh)||/\bthe word\b.*\bmeans\b|\bword\s+['“"]?\w+['”"]?\s+(?:means|is used)/i.test(ex.en))errors.push(`${row.id}: missing or placeholder example`);
  }
  result[row.id]=row.entries;
 }
}
const missing=[...expected].filter(id=>!result[id]);
const report={expectedWords:expected.size,completedWords:Object.keys(result).length,meanings:Object.values(result).flat().length,examples:Object.values(result).flat().reduce((n,e)=>n+(e.examples?.length||0),0),missing,errors};
await mkdir(join(root,'outputs/word-learning'),{recursive:true});
await writeFile(join(root,'outputs/word-learning/enrichment-coverage.json'),JSON.stringify(report,null,2)+'\n');
if(errors.length||missing.length&&!process.argv.includes('--partial')){console.error(JSON.stringify({...report,missing:missing.slice(0,20),errors:errors.slice(0,20)},null,2));process.exitCode=1;}
else{
 const sorted=Object.fromEntries(Object.keys(result).sort().map(id=>[id,result[id]]));
 const output='// Generated by scripts/build-word-enrichment.mjs from original bilingual teaching material.\nexport const wordEnrichment = '+JSON.stringify(sorted)+';\n';
 await writeFile(join(root,'dist/word-enrichment.js'),output);await writeFile(join(root,'word-enrichment.js'),output);
 console.log(JSON.stringify({words:report.completedWords,meanings:report.meanings,examples:report.examples,remaining:missing.length,partial:missing.length>0}));
}
